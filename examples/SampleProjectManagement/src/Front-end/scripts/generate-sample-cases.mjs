import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const frontendRoot = resolve(scriptDirectory, '..');
const registryPath = resolve(frontendRoot, '..', '..', 'docs', 'cases', 'sample-case-registry.json');
const outputPath = resolve(
  frontendRoot,
  'projects',
  'sample-project-management-common',
  'src',
  'lib',
  'sample-cases.ts'
);

const registry = JSON.parse(await readFile(registryPath, 'utf8'));
if (registry.schemaVersion !== 1 || !Array.isArray(registry.categories) || !Array.isArray(registry.cases)) {
  throw new Error('Invalid sample case registry.');
}
if (registry.cases.length < 100) throw new Error(`Expected at least 100 sample cases, found ${registry.cases.length}.`);

const categories = new Map(registry.categories.map(category => [category.id, category.title]));
const ids = new Set();
const cases = registry.cases.map(item => {
  if (ids.has(item.id)) throw new Error(`Duplicate sample case: ${item.id}`);
  ids.add(item.id);
  const category = categories.get(item.categoryId);
  if (!category) throw new Error(`${item.id} uses unknown category ${item.categoryId}.`);
  return {
    id: item.id,
    title: item.title.replaceAll('`', ''),
    category,
    surface: item.surface.replaceAll('`', ''),
    outcome: item.outcome,
    implementation: item.implementation,
    ...(item.statusReason ? { statusReason: item.statusReason } : {}),
    evidence: item.evidence ?? []
  };
});

const source = `// Generated by scripts/generate-sample-cases.mjs from docs/cases/sample-case-registry.json.\n` +
`// Do not edit this file by hand.\n\n` +
`export type SampleCaseImplementation = 'implemented' | 'partial' | 'planned' | 'library-gap';\n\n` +
`export interface SampleCase {\n` +
`  id: string;\n` +
`  title: string;\n` +
`  category: string;\n` +
`  surface: string;\n` +
`  outcome: string;\n` +
`  implementation: SampleCaseImplementation;\n` +
`  statusReason?: string;\n` +
`  evidence: readonly string[];\n` +
`}\n\n` +
`export const SAMPLE_CASES: readonly SampleCase[] = ${JSON.stringify(cases, null, 2)} as const;\n`;

await mkdir(dirname(outputPath), { recursive: true });
let current;
try { current = await readFile(outputPath, 'utf8'); } catch { current = undefined; }
if (current?.replaceAll('\r\n', '\n') !== source.replaceAll('\r\n', '\n')) {
  await writeFile(outputPath, source, 'utf8');
}
console.log(`Generated ${cases.length} sample cases from the canonical registry.`);
